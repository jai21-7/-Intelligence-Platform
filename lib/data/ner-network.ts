/** Junction ids are reused as graph node ids in the routing engine. */
export const JUNCTIONS: Junction[] = DISTRICTS.map((d) => ({
  id: d.id,
  name: `${d.name} HQ`,
  districtId: d.id,
  position: d.hq,
}));

/**
 * Helper: a slightly bent polyline so roads do not look like laser beams.
 * Real GIS would store surveyed polylines from NHAI / OpenStreetMap.
 */
function via(a: Junction["position"], b: Junction["position"], bump = 0.12): Junction["position"][] {
  return [
    a,
    {
      lat: (a.lat + b.lat) / 2 + bump * 0.15,
      lng: (a.lng + b.lng) / 2 - bump * 0.05,
    },
    b,
  ];
}

function j(id: string) {
  const found = JUNCTIONS.find((x) => x.id === id);
  if (!found) throw new Error(`Unknown junction ${id}`);
  return found.position;
}

